def convert_path_to_df(dataset):
    image_dir = Path(dataset)

    # Get filepaths for all supported formats
    extensions = ['*.jpg', '*.JPG', '*.jpeg', '*.png', '*.PNG']
    filepaths = []
    for ext in extensions:
        filepaths.extend(list(image_dir.glob(f'**/{ext}')))

    # Extract labels using pathlib (more robust than os.path.split)
    labels = [x.parent.name for x in filepaths]

    filepaths = pd.Series(filepaths, name='Filepath').astype(str)
    labels = pd.Series(labels, name='Label')

    df = pd.concat([filepaths, labels], axis=1)

    # Identify unique classes and their count
    unique_classes = df['Label'].unique()
    num_classes = len(unique_classes)

    return df, num_classes, unique_classes

