def print_images_resolution(directory, limit=10):
    total_images = 0

    # Iterasi setiap folder kelas
    for subdir in sorted(os.listdir(directory)):
        subdir_path = os.path.join(directory, subdir)
        if not os.path.isdir(subdir_path):
            continue

        image_files = os.listdir(subdir_path)
        num_images = len(image_files)
        print(f"📁 {subdir}: {num_images} images")
        total_images += num_images

        # Gunakan set untuk mencari ukuran unik, tapi kita batasi prosesnya
        unique_sizes = set()

        # islice akan berhenti membaca file setelah mencapai batas 'limit'
        # Ini jauh lebih cepat daripada membaca ribuan gambar
        for img_file in islice(image_files, limit):
            img_path = os.path.join(subdir_path, img_file)
            try:
                with Image.open(img_path) as img:
                    unique_sizes.add(img.size)
            except:
                continue # Lewati jika ada file yang bukan gambar atau korup

        # Cetak sampel resolusi yang ditemukan
        for size in unique_sizes:
            print(f"   - Sample Resolution: {size}")

        print("-" * 30)

    print(f"\n✅ Total Images in Dataset: {total_images}")

