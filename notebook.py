# 1. Callback Tunggal untuk Live Log, Rename Metrik, & Threshold
class MyAnimalCallback(tf.keras.callbacks.Callback):
    def __init__(self, val_gen, threshold=0.96):
        super().__init__()
        self.val_gen = val_gen
        self.threshold = threshold

    def on_epoch_begin(self, epoch, logs=None):
        # Ambil Learning Rate saat ini
        lr = self.model.optimizer.learning_rate
        self.curr_lr = lr.numpy() if hasattr(lr, 'numpy') else tf.keras.backend.get_value(lr)

    def on_train_batch_end(self, batch, logs=None):
        # Ambil sampel kecil untuk Live Validation
        val_imgs, val_lbls = next(self.val_gen)
        val_m = self.model.test_on_batch(val_imgs, val_lbls, return_dict=True)

        # Rename dan Masukkan ke Bar Progres
        logs['train_acc'] = logs.pop('accuracy', 0)
        logs['train_loss'] = logs.pop('loss', 0)
        logs['val_acc'] = val_m['accuracy']
        logs['val_loss'] = val_m['loss']
        logs['lr'] = self.curr_lr

    def on_epoch_end(self, epoch, logs=None):
        # Ambil hasil akhir (evaluasi total oleh Keras)
        ta = logs.get('train_acc', logs.get('accuracy'))
        tl = logs.get('train_loss', logs.get('loss'))
        va = logs.get('val_accuracy')
        vl = logs.get('val_loss')

        print(f"\n" + "="*55)
        print(f"✨ EPOCH {epoch+1} SELESAI")
        print(f"📈 Train: Acc {ta:.4f} | Loss {tl:.4f}")
        print(f"🧪 Valid: Acc {va:.4f} | Loss {vl:.4f}")
        print(f"💡 LR: {self.curr_lr:.2e}")
        print("="*55 + "\n")

        if ta >= self.threshold and va >= self.threshold:
            print(f"🚀 Reached {self.threshold*100}% - STOPPING TRAINING!")
            self.model.stop_training = True

# 2. Scheduler & Eksekusi
